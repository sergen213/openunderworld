#!/usr/bin/env python3
"""Generate the "Counts" paragraph of docs/REFERENCE_COMPARISON.md from its mechanic tables.

The paragraph sits between the two `comparison-counts` marker comments under "## Counts". It is computed with
the same parser as the progress site (progress.parse_comparison: one count per row of every `| ID | Mechanic |
... | Status |` table, sub-rows of a mechanic counted separately), so the document and the site cannot disagree.

    python3 tools/progress/comparison_counts.py           # rewrite the paragraph in place
    python3 tools/progress/comparison_counts.py --check   # exit 1 if the committed paragraph is out of date
"""

import argparse
import re
import sys
import textwrap
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import progress as p  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
BEGIN = "<!-- comparison-counts:begin (generated by tools/progress/comparison_counts.py; do not edit by hand) -->"
END = "<!-- comparison-counts:end -->"


def table_rows(lines: list[str]) -> list[list[str]]:
    """Every row of the mechanic tables, in document order (the tables parse_comparison counts)."""
    out, pos = [], 0
    while True:
        try:
            _, _, rows = p.table_after(lines, pos, lambda h: h[:2] == ["ID", "Mechanic"], "comparison")
        except p.ParseError as e:
            if out and "not found" in str(e):
                return out
            raise
        out.extend(row for _, row in rows)
        pos = rows[-1][0] + 1


def ids_of(rows: list[list[str]], kind: str) -> list[str]:
    """IDs of the rows of one status kind; a row without an ID is named by its mechanic."""
    seen = []
    for row in rows:
        if p.cmp_kind(row[-1]) == kind:
            rid = p.plain(row[0])
            if rid in ("", "—", "-"):
                rid = re.sub(r"\s*\(.*\)\s*$", "", p.plain(row[1]))
            if rid not in seen:
                seen.append(rid)
    return seen


def paragraph(text: str) -> str:
    c = p.parse_comparison(text)
    rows = table_rows(text.splitlines())
    n = c["counts"]
    live = sum(1 for row in rows if any("O-runtime" in cell for cell in row))
    differs = ", ".join(ids_of(rows, "differs")) or "none"
    part = ", ".join(ids_of(rows, "match_part_differs")) or "none"
    body = (
        f"{c['total']} rows: **{c['matching']}** match ({n['match_part_differs']} of them with a part that differs: "
        f"{part}), **{n['differs']}** differ ({differs}), **{n['unmeasured']}** are unmeasured. {live} rows cite a "
        "live measurement of the original ([O-runtime]); the rest are decoded only (†). Counted over every row of the "
        "mechanic tables (`| ID | Mechanic | ... | Status |`), a mechanic's sub-rows separately, by the status word "
        "the Status cell starts with (`matches`, `differs`, `unmeasured`; `matches` with `differs` later in the cell "
        "= a part differs) — the same count as the progress site (tools/progress/progress.py).")
    wrapped = textwrap.wrap(body, width=118, break_long_words=False, break_on_hyphens=False)
    return "\n".join([BEGIN, *wrapped, END])


def replace(text: str) -> str:
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise p.ParseError("comparison counts: marker comments not found under '## Counts'")
    return pattern.sub(lambda _: paragraph(text), text, count=1)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed paragraph is out of date")
    args = ap.parse_args()
    path = ROOT / p.COMPARISON
    text = path.read_text()
    new = replace(text)
    if args.check:
        if new != text:
            print(f"{p.COMPARISON}: Counts paragraph out of date; run tools/progress/comparison_counts.py",
                  file=sys.stderr)
            return 1
        return 0
    if new != text:
        path.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
